// Par data (DESIGN.md "Progression, scores, and fanfare"): replays every campaign level's authored
// solution through the real physics (seed 7, normal pace) and writes src/levels/par.ts.
//   moves       = hero inputs (each U/D/L/R and each K+dir counts 1) for hero levels, drags otherwise
//   seconds     = sim time to the win, settles included (0.1 s)
//   sandSeconds = sim time during which at least one grain crossed into a box (0.1 s)
// Usage: npm run par            (rewrites src/levels/par.ts; idempotent: same levels, same file)
//        npm run par -- --check (exit 1 if the file on disk is stale, without writing)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LEVELS } from '../src/levels';
import { replayLevel } from '../src/levels/replay';
import { STEPS_PER_SECOND } from '../src/core/constants';

const out = fileURLToPath(new URL('../src/levels/par.ts', import.meta.url));
const r1 = (steps: number) => Math.round((steps / STEPS_PER_SECOND) * 10) / 10;

const rows: string[] = [];
let failed = 0;
for (const level of LEVELS) {
  const r = replayLevel(level, level.solution ?? [], { seed: 7 });
  if (!r.won) {
    console.error(`✗ ${level.id}: ${r.why}`);
    failed++;
    continue;
  }
  const moves = level.hero ? r.inputs : r.drags;
  const sandSteps = r.state.events.filter((e) => e.type === 'transfer').length;
  rows.push(`  ${JSON.stringify(level.id)}: { moves: ${moves}, seconds: ${r1(r.steps)}, sandSeconds: ${r1(sandSteps)} },`);
}
if (failed) {
  console.error(`${failed} level(s) did not win; par not written`);
  process.exit(1);
}

const text = `// GENERATED by \`npm run par\` (scripts/par.ts) from the authored solutions replayed through the
// physics (seed 7, normal pace). Do not edit by hand; rerun after changing a level or the physics.
// moves = hero inputs (a kick counts 1) or drags; seconds = sim time to win; sandSeconds = sim time
// during which sand was flowing into a box.

export interface Par {
  moves: number;
  seconds: number;
  sandSeconds: number;
}

export const PAR: Record<string, Par> = {
${rows.join('\n')}
};

/** Par for a campaign level id, or undefined (generated / free-play levels have none). */
export function parFor(id: string): Par | undefined {
  return Object.prototype.hasOwnProperty.call(PAR, id) ? PAR[id] : undefined;
}
`;

let old = '';
try {
  old = readFileSync(out, 'utf8');
} catch {
  // first run
}
if (process.argv.includes('--check')) {
  console.log(old === text ? 'par is up to date' : 'par is STALE: run npm run par');
  process.exit(old === text ? 0 : 1);
}
if (old === text) console.log(`par unchanged (${rows.length} levels)`);
else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${rows.length} levels)`);
}
